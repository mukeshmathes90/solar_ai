"""Dataset generator for the renewable microgrid demo.

Produces a physically plausible, fully labelled time-series dataset for a small
hybrid solar + wind microgrid node (ESP8266 + 6 V solar panel + small DC
dynamo + DHT11 + LDR + KY-024 hall sensor).

IMPORTANT HONESTY NOTE
----------------------
Every value produced here is **generated by this script** from a reproducible
model, not a field measurement.  The columns ending in ``_est_a`` are
*estimated* currents derived from the same model.  A real node without a
connected load / battery cannot measure generated current through an INA219;
those fields are therefore reported as ``null`` by the live firmware.  This
dataset exists so the machine-learning pipeline, API and dashboard can be
developed and demonstrated without hardware, and so that real sensor logs can
replace it later.

Usage
-----
    python -m ml.generate_dataset --rows 12000 --seed 42
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path
from typing import Dict

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from config import settings  # noqa: E402

# --------------------------------------------------------------------------- #
# Hardware constants used by the simulation (shared with config.settings so the
# live inference service engineers identical features).
# --------------------------------------------------------------------------- #
SOLAR_VOC = settings.SOLAR_VOC
SOLAR_IRR_REF = settings.SOLAR_IRR_REF
SOLAR_ISC = 0.35           # A at 1000 W/m2
WIND_GEN_K = 0.0052        # V per RPM after the rectifier drop
WIND_RECT_DROP = 0.60      # V, bridge-rectifier forward drop
WIND_ISC_RATED = 0.28      # A at the rated 1200 RPM
WIND_RPM_MAX = 1200.0
WIND_CUT_IN_MS = 2.0       # m/s
WIND_RATED_MS = 11.0
WIND_STALL_MS = 14.0

START_TIMESTAMP = "2025-01-01 00:00:00"
SAMPLE_PERIOD = "5min"

CONDITION_NORMAL = "normal"
CONDITION_REDUCED = "reduced_generation"
CONDITION_NIGHT = "night_idle"
CONDITION_FAULT = "fault"


def _ar1(rng: np.random.Generator, n: int, rho: float, sigma: float,
         start: float = 0.0) -> np.ndarray:
    """Stationary AR(1) process: x[t] = rho*x[t-1] + N(0, sigma)."""
    out = np.empty(n, dtype=float)
    out[0] = start
    for i in range(1, n):
        out[i] = rho * out[i - 1] + rng.normal(0.0, sigma)
    return out


def _scattered_windows(rng: np.random.Generator, rows: int, count: int,
                       min_width: int, max_width: int):
    """Yield (start, end) spans spread evenly across the whole timeline.

    Drawing window centres uniformly at random clusters them by chance, which
    after a chronological train/test split can leave a class almost absent from
    the test set.  Anchoring one window per time-slice with jitter guarantees
    every split sees the same mix of conditions.
    """
    if rows <= max_width + 2:
        return
    edges = np.linspace(0, rows - max_width - 1, count + 1)
    for index in range(count):
        low = int(edges[index])
        high = int(edges[index + 1]) - min_width
        start = int(rng.integers(low, max(low + 1, high)))
        width = int(rng.integers(min_width, max_width))
        yield start, min(start + width, rows)


def _solar_curve(irradiance: np.ndarray, temperature: np.ndarray,
                 rng: np.random.Generator) -> np.ndarray:
    """Terminal voltage of a small panel for a given irradiance and cell temp."""
    thermal = 1.0 - settings.SOLAR_TEMP_COEF * (temperature - 25.0)
    voltage = SOLAR_VOC * (1.0 - np.exp(-irradiance / SOLAR_IRR_REF)) * thermal
    voltage += 0.12 + rng.normal(0.0, 0.045, irradiance.shape)
    return np.clip(voltage, 0.0, 7.5)


def _wind_rpm(wind_speed: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    """Propeller RPM curve: cut-in, near-linear rise, stall above rated speed."""
    rpm = np.zeros_like(wind_speed)
    active = wind_speed > WIND_CUT_IN_MS
    span = max(WIND_RATED_MS - WIND_CUT_IN_MS, 1e-6)
    frac = (wind_speed[active] - WIND_CUT_IN_MS) / span
    frac = np.clip(frac, 0.0, 1.0)
    rpm[active] = WIND_RPM_MAX * np.power(frac, 0.9)

    stalled = wind_speed > WIND_STALL_MS
    rpm[stalled] *= 0.72  # blades stall / controller derates above ~14 m/s

    rpm += rng.normal(0.0, 22.0, rpm.shape)
    rpm += _ar1(rng, rpm.shape[0], 0.90, 6.0)  # mechanical inertia
    return np.clip(rpm, 0.0, WIND_RPM_MAX * 1.05)


def _wind_voltage(rpm: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    """Rectified dynamo voltage."""
    voltage = WIND_GEN_K * rpm - WIND_RECT_DROP
    voltage += rng.normal(0.0, 0.04, rpm.shape)
    return np.clip(voltage, 0.0, 9.0)


def generate(rows: int = 12000, seed: int = 42) -> pd.DataFrame:
    """Build the full simulated dataset.  Fully reproducible for a given seed."""
    if rows < 100:
        raise ValueError("rows must be >= 100")
    rng = np.random.default_rng(seed)

    index = pd.date_range(START_TIMESTAMP, periods=rows, freq=SAMPLE_PERIOD)
    hour = index.hour.to_numpy() + index.minute.to_numpy() / 60.0
    day_of_year = index.day_of_year.to_numpy()

    # ------------------------------------------------------------------ #
    # Weather
    # ------------------------------------------------------------------ #
    cloud_ar = _ar1(rng, rows, rho=0.985, sigma=0.055)
    cloud = 0.72 + cloud_ar
    cloud = np.clip(cloud, 0.18, 1.05)

    # A handful of explicit overcast stretches so the plots show weather variety.
    for centre, end in _scattered_windows(rng, rows, count=10,
                                          min_width=80, max_width=400):
        cloud[centre:end] *= rng.uniform(0.35, 0.6)

    altitude = np.sin(np.pi * (hour - 6.0) / 12.0)
    altitude = np.where((hour >= 6.0) & (hour <= 18.0), altitude, 0.0)
    altitude = np.clip(altitude, 0.0, 1.0)
    clear_sky = 1000.0 * np.power(altitude, 1.15)
    irradiance = clear_sky * cloud + rng.normal(0.0, 12.0, rows)
    irradiance = np.clip(irradiance, 0.0, 1050.0)

    temperature = (
        24.0
        + 7.0 * np.sin(2.0 * np.pi * (hour - 9.0) / 24.0)
        + 2.5 * np.sin(2.0 * np.pi * day_of_year / 365.0)
        + _ar1(rng, rows, rho=0.97, sigma=0.35)
    )
    temperature = np.clip(temperature, 12.0, 41.0)

    humidity = (
        62.0
        - 18.0 * np.sin(2.0 * np.pi * (hour - 9.0) / 24.0)
        + _ar1(rng, rows, rho=0.985, sigma=0.9)
    )
    humidity = np.clip(humidity, 18.0, 97.0)

    wind_speed = (
        4.2
        + 2.1 * np.sin(2.0 * np.pi * hour / 24.0 + 1.1)
        + 1.6 * np.sin(2.0 * np.pi * day_of_year / 21.0)
        + _ar1(rng, rows, rho=0.965, sigma=0.42)
    )
    for centre, end in _scattered_windows(rng, rows, count=8,
                                          min_width=40, max_width=200):
        wind_speed[centre:end] += rng.uniform(3.0, 8.0)
    wind_speed = np.clip(wind_speed, 0.0, 16.5)

    light_lux = np.clip(
        settings.LUX_OFFSET
        + settings.LUX_SCALE * np.power(irradiance / 1000.0, settings.LUX_EXPONENT),
        0.0,
        settings.LUX_OFFSET + settings.LUX_SCALE * 1.03,
    )

    # ------------------------------------------------------------------ #
    # Clean power model
    # ------------------------------------------------------------------ #
    solar_voltage = _solar_curve(irradiance, temperature, rng)
    solar_current = SOLAR_ISC * (irradiance / 1000.0) * (1 + 0.002 * (temperature - 25.0))
    solar_current = np.clip(solar_current + rng.normal(0.0, 0.006, rows), 0.0, 0.6)

    turbine_rpm = _wind_rpm(wind_speed, rng)
    wind_voltage = _wind_voltage(turbine_rpm, rng)
    wind_current = WIND_ISC_RATED * (turbine_rpm / WIND_RPM_MAX)
    wind_current = np.clip(wind_current + rng.normal(0.0, 0.005, rows), 0.0, 0.45)

    solar_power = solar_voltage * solar_current
    wind_power = wind_voltage * wind_current
    total_power = solar_power + wind_power

    # Name-plate output the system *should* deliver right now (clean, unshaded).
    expected_total = total_power.copy()

    # ------------------------------------------------------------------ #
    # Non-fault generation loss: dust/soiling, partial shading, becalming.
    # These are legitimate low-output periods, not equipment failures.
    # ------------------------------------------------------------------ #
    soiling = 1.0 - 0.10 * np.clip(_ar1(rng, rows, rho=0.9995, sigma=0.02), 0.0, None)
    soiling = np.clip(soiling, 0.86, 1.0)
    for centre, end in _scattered_windows(rng, rows, count=30,
                                          min_width=40, max_width=130):
        soiling[centre:end] *= rng.uniform(0.28, 0.58)
    # Shading/soiling cuts photocurrent, and partial shading additionally
    # lowers MPP voltage through cell-string mismatch (observable by the model).
    solar_current = solar_current * soiling
    solar_voltage = solar_voltage * (0.35 + 0.65 * soiling)

    becalmed = 1.0 - 0.12 * np.clip(_ar1(rng, rows, rho=0.999, sigma=0.02), 0.0, None)
    becalmed = np.clip(becalmed, 0.88, 1.0)
    for centre, end in _scattered_windows(rng, rows, count=14,
                                          min_width=40, max_width=120):
        becalmed[centre:end] *= rng.uniform(0.32, 0.62)
    wind_current = wind_current * becalmed
    # Bearing wear / fouling also lowers the generator constant, so the
    # voltage produced per RPM drops - again visible in the sensor vector.
    wind_voltage = wind_voltage * (0.30 + 0.70 * becalmed)

    solar_power = solar_voltage * solar_current
    wind_power = wind_voltage * wind_current
    total_power = solar_power + wind_power

    # ------------------------------------------------------------------ #
    # Injected faults  (labelled so supervised learning has a target)
    # ------------------------------------------------------------------ #
    anomaly_type = np.full(rows, "none", dtype=object)
    fault_rnd = rng.random(rows)

    mask_sensor = fault_rnd < 0.020                      # DHT11 out of range
    temperature = np.where(mask_sensor, rng.choice([-25.0, 88.0, 120.0], rows),
                           temperature)
    humidity = np.where(mask_sensor & (rng.random(rows) < 0.5), 100.0, humidity)
    anomaly_type[mask_sensor] = "sensor_fault"

    mask_stuck = (~mask_sensor) & (fault_rnd >= 0.020) & (fault_rnd < 0.026)
    stuck_value = float(turbine_rpm[rows // 2])
    turbine_rpm = np.where(mask_stuck, stuck_value, turbine_rpm)
    anomaly_type[mask_stuck] = "sensor_stuck"

    mask_drop = (fault_rnd >= 0.030) & (fault_rnd < 0.052)      # shaded / dirty panel
    solar_voltage = np.where(mask_drop, solar_voltage * 0.35, solar_voltage)
    solar_current = np.where(mask_drop, solar_current * 0.15, solar_current)
    anomaly_type[mask_drop] = "generation_drop"

    mask_mismatch = (fault_rnd >= 0.055) & (fault_rnd < 0.072)  # broken generator
    wind_voltage = np.where(mask_mismatch, 0.05, wind_voltage)
    wind_current = np.where(mask_mismatch, 0.0, wind_current)
    anomaly_type[mask_mismatch] = "voltage_rpm_mismatch"

    mask_spike = (fault_rnd >= 0.075) & (fault_rnd < 0.085)     # over-voltage spike
    wind_voltage = np.where(mask_spike, wind_voltage * 1.65 + 0.9, wind_voltage)
    anomaly_type[mask_spike] = "overvoltage_spike"

    solar_power = solar_voltage * solar_current
    wind_power = wind_voltage * wind_current
    total_power = solar_power + wind_power
    anomaly_label = (anomaly_type != "none").astype(int)

    # ------------------------------------------------------------------ #
    # Operating condition
    # ------------------------------------------------------------------ #
    condition = np.full(rows, CONDITION_NORMAL, dtype=object)
    night = (irradiance < 15.0) & (turbine_rpm < 100.0)
    # A "reduced generation" period is one where a legitimate, non-fault loss
    # mechanism (partial shading / soiling, or turbine fouling / light wind)
    # has pulled output well below the clean name-plate value.  The label is
    # derived from the loss factors themselves, all of which leave a clear
    # fingerprint in the measurable voltage/irradiance/RPM vector.
    degraded = (soiling < 0.80) | (becalmed < 0.80)
    degraded &= expected_total > 0.05
    condition[degraded] = CONDITION_REDUCED
    condition[night] = CONDITION_NIGHT
    condition[anomaly_label == 1] = CONDITION_FAULT

    frame = pd.DataFrame(
        {
            "timestamp": index,
            "data_origin": "simulated",
            "device_id": "SIM-GRID-01",
            "solar_voltage": np.round(solar_voltage, 3),
            "solar_irradiance_wm2": np.round(irradiance, 1),
            "wind_voltage": np.round(wind_voltage, 3),
            "turbine_rpm": np.round(turbine_rpm, 1),
            "temperature_c": np.round(temperature, 2),
            "humidity_percent": np.round(humidity, 2),
            "light_level_lux": np.round(light_lux, 0),
            "wind_speed_ms": np.round(wind_speed, 2),
            "soiling_factor": np.round(soiling, 4),
            "turbine_efficiency": np.round(becalmed, 4),
            "clear_sky_power_w": np.round(expected_total, 4),
            "solar_current_est_a": np.round(solar_current, 4),
            "wind_current_est_a": np.round(wind_current, 4),
            "solar_power_est_w": np.round(solar_power, 4),
            "wind_power_est_w": np.round(wind_power, 4),
            "total_est_power_w": np.round(total_power, 4),
            "operating_condition": condition,
            "anomaly_label": anomaly_label,
            "anomaly_type": anomaly_type,
        }
    )

    if frame.isna().any().any():
        raise RuntimeError("generator produced unexpected null values")
    if len(frame) != rows:
        raise RuntimeError("generator row count mismatch")

    # Persist the same engineered diagnostics the models consume, so the CSV is
    # self-describing and the report graphs can use them directly.
    from ml import preprocess  # local import: avoids a cycle at module load

    frame = preprocess.engineer_features(frame)
    return frame


def summarise(frame: pd.DataFrame) -> Dict[str, object]:
    """Compact statistics printed by the CLI and stored next to the dataset."""
    return {
        "rows": int(len(frame)),
        "columns": list(frame.columns),
        "start": str(frame["timestamp"].min()),
        "end": str(frame["timestamp"].max()),
        "nulls": int(frame.isna().sum().sum()),
        "duplicated_timestamps": int(frame["timestamp"].duplicated().sum()),
        "anomaly_rate": round(float(frame["anomaly_label"].mean()), 4),
        "condition_counts": {
            str(k): int(v)
            for k, v in frame["operating_condition"].value_counts().items()
        },
        "anomaly_type_counts": {
            str(k): int(v)
            for k, v in frame["anomaly_type"].value_counts().items()
        },
        "ranges": {
            col: [
                round(float(frame[col].min()), 4),
                round(float(frame[col].max()), 4),
            ]
            for col in [
                "solar_voltage",
                "solar_irradiance_wm2",
                "wind_voltage",
                "turbine_rpm",
                "temperature_c",
                "humidity_percent",
                "total_est_power_w",
            ]
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rows", type=int, default=12000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=str, default=str(settings.DATASET_PATH))
    args = parser.parse_args()

    settings.ensure_directories()
    frame = generate(rows=args.rows, seed=args.seed)
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(out_path, index=False)

    info = summarise(frame)
    info["seed"] = args.seed
    info["sample_period"] = SAMPLE_PERIOD
    print("Dataset written to: %s" % out_path)
    print("Rows               : %d" % info["rows"])
    print("Anomaly rate       : %.2f%%" % (100.0 * info["anomaly_rate"]))
    print("Conditions         : %s" % info["condition_counts"])
    print("Anomaly types      : %s" % info["anomaly_type_counts"])
    print("Null cells         : %d" % info["nulls"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
